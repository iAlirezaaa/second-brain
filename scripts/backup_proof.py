#!/usr/bin/env python
"""The restore half of the backup promise, run by a second machine instead of asserted by one.

`scripts/vault.py` can seal the private planes. That proves a container was written; it does not
prove the bytes come back. Section 8 of the charter asks for both halves -- an encrypted backup
*and* a restore test actually run -- and the failure mode this script exists to catch is the one a
single machine cannot see: a container that only its own writer can open, because of a path rule,
an end-of-line, a filesystem detail, or a bug in the reader that no seal ever exercises.

Three commands, one per side of the transfer:

  python scripts/backup_proof.py --fixture [--root DIR]
  python scripts/backup_proof.py --seal --passphrase-file PATH --envelope PATH [--kdf ID] [--ci-run ID]
  python scripts/backup_proof.py --restore --envelope PATH --passphrase-file PATH --into DIR

`--fixture` writes a synthetic, non-personal private plane and refuses to run where a plane already
holds files: this proof must never read the owner's vault, and it must never be the thing that
finally made a real note disappear. `--seal` seals, then re-opens what it wrote and compares.
`--restore` carries the bytes back into a directory that did not exist and re-measures everything it
can from disk.

Two laws make the pair worth running rather than theatrical:

* The restoring host must not be the sealing host. `--restore` reads `platform.node()` and refuses
  when it equals the recorded `sealed_on`, unless `--allow-same-machine` is passed -- in which case
  it prints `cross_machine: false` and says the run is not evidence. A "recovery test" run on the
  machine that just wrote the file is the oldest way to fake a backup.
* Nothing here opens a door. This script writes no file inside the repository, records no witness,
  and flips no flag. `11_CONTROL/backups/verification.json` is written by a human who read a real
  run, and `scripts/vault_check.py` is the door that judges it.

What the proof cannot verify is *where* the seal happened -- a host name is self-reported. The
independent witness for that is the CI run id recorded as `ci_run` and the two different OS images
the job pair runs on. The passphrase travels in the same ephemeral artifact as the container, so
what this pair proves is the round trip of bytes across machines and Python versions, not
confidentiality; on a real vault the key never leaves the owner's terminal.
"""
import hashlib
import json
import platform
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, str(Path(__file__).parent.parent / "15_SYSTEM" / "scripts"))
import common  # noqa: E402
from backend import crypto, vault  # noqa: E402

EXIT_OK, EXIT_REFUSED, EXIT_USAGE = 0, 1, 2

COMMANDS = ("--fixture", "--seal", "--restore")
VALUE_FLAGS = ("--root", "--passphrase-file", "--envelope", "--into", "--kdf", "--ci-run")
SWITCHES = ("--allow-same-machine", "--witness")

# The envelope is what machine B hands to its own check. It carries no `id` and no `kind`, because
# `hades.py::iter_records` reads those as a registry record -- and it is only ever written outside
# the repository, so it can never become self-issued evidence.
ENVELOPE_KEYS = ("name", "cipher", "kdf", "container_sha256", "plain_bytes", "files",
                 "plane_digest", "planes", "sealed_on", "sealed_platform", "sealed_python",
                 "sealed_at", "ci_run")

NOT_A_CI_RUN = "not-a-ci-run"

# Synthetic by construction: no names, no dates, nothing that could be read as a person's note.
# Fixed bytes, so a digest disagreement means the mechanism moved, not the content.
FIXTURE_LEAVES = (
    ("synthetic-note-a.txt", 900),
    ("nested/synthetic-note-b.txt", 2400),
    ("synthetic-index.jsonl", 1500),
)
FIXTURE_BANNER = ("HADES cross-machine backup proof. Synthetic content, generated by "
                  "scripts/backup_proof.py --fixture. Not personal data. ")


def payload(plane, rel, size):
    head = ("%s/%s|" % (plane, rel)).encode("utf-8")
    body = bytearray()
    counter = 0
    while len(body) + len(head) + len(FIXTURE_BANNER.encode("utf-8")) < size:
        body += ("%06d " % counter).encode("ascii")
        counter += 1
    return head + FIXTURE_BANNER.encode("utf-8") + bytes(body)


def refuse(message):
    print("REFUSED: %s" % message)
    return EXIT_REFUSED


def usage(problem=None):
    if problem:
        print("REFUSED: %s" % problem)
    print("USAGE: one of --fixture | --seal | --restore, each with the options its header names")
    print("  (run `python scripts/backup_proof.py` with no arguments and read the module docstring)")
    return EXIT_USAGE


def outside_repo(path, root, what):
    candidate = Path(path).resolve()
    try:
        candidate.relative_to(Path(root).resolve())
    except ValueError:
        return candidate
    raise ValueError("%s %s resolves inside the repository: this proof neither writes nor reads"
                     " a claim that a commit could carry as evidence" % (what, path))


def plane_digest(files):
    """One digest rule for the whole proof: {rel path: sha1(bytes)} fed to the base fingerprint."""
    return common.fingerprint_of_inventory(
        dict((rel, hashlib.sha1(payload_bytes).hexdigest()) for rel, payload_bytes in files))


def disk_digest(into):
    files = []
    for path in sorted(Path(into).rglob("*")):
        if path.is_file():
            files.append((path.relative_to(into).as_posix(), path.read_bytes()))
    return plane_digest(files), len(files), sum(len(b) for _, b in files)


def parse(argv):
    """{command, options}. Refuses unknown, duplicated or value-less flags before anything runs."""
    if not argv:
        raise ValueError("no command given")
    commands = [arg for arg in argv if arg in COMMANDS]
    if len(commands) != 1:
        raise ValueError("exactly one of %s is required, got %d"
                         % (", ".join(COMMANDS), len(commands)))
    opts = dict((flag, None) for flag in VALUE_FLAGS)
    switches = dict((flag, False) for flag in SWITCHES)
    index = 0
    while index < len(argv):
        arg = argv[index]
        if arg in COMMANDS:
            index += 1
            continue
        if arg in switches:
            switches[arg] = True
            index += 1
            continue
        if arg in opts:
            if index + 1 >= len(argv) or argv[index + 1] in COMMANDS or argv[index + 1] in opts \
                    or argv[index + 1] in switches:
                raise ValueError("%s needs a value" % arg)
            opts[arg] = argv[index + 1]
            index += 2
            continue
        raise ValueError("unknown argument %r" % arg)
    result = dict((flag[2:], value) for flag, value in switches.items())
    result["command"] = commands[0]
    for flag, value in opts.items():
        if value is not None:
            result[flag[2:]] = value
    return result


def host_law(here, sealed_on, opts):
    """Raise before a byte is placed when this machine is the machine that wrote the container.

    A refusal under this law must not restore anything: a "recovery test" that only announces
    itself after the fact has already moved the data it claims not to trust.
    """
    if str(here).casefold() == str(sealed_on).casefold() and not opts["allow-same-machine"]:
        raise ValueError("this machine is %s, which is also where the container was sealed. Restore"
                         " on another host, or pass --allow-same-machine to get a byte check that"
                         " names itself as not evidence." % here)


def cmd_fixture(root):
    planes = vault.plane_list(vault.read_config(root))
    for plane in planes:
        base = Path(root) / plane
        if base.is_dir() and any(path.is_file() for path in base.rglob("*")):
            return refuse("private plane %s already holds files. This proof only seals bytes it"
                          " wrote itself, so it will not read -- or become responsible for -- a"
                          " real vault." % plane)
    written = 0
    for plane in planes:
        base = Path(root) / plane
        for rel, size in FIXTURE_LEAVES:
            target = base / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(payload(plane, rel, size))
            written += 1
    print("FIXTURE %d synthetic file(s) across %d plane(s): %s"
          % (written, len(planes), ", ".join(planes)))
    print("SYNTHETIC ONLY nothing here is a person's note; a real vault is never written by this"
          " command")
    return EXIT_OK


def cmd_seal(root, opts):
    planes = vault.plane_list(vault.read_config(root))
    missing = [plane for plane in planes if not (Path(root) / plane).is_dir()]
    if missing:
        return refuse("declared private plane(s) absent: %s. Sealing three of four planes is a"
                      " backup that lies about the fourth." % ", ".join(missing))
    envelope_path = outside_repo(opts.get("envelope"), root, "--envelope")
    if envelope_path.exists():
        return refuse("--envelope %s already exists; a proof does not overwrite the numbers it is"
                      " about to claim." % envelope_path)
    key = vault.passphrase_from_file(opts["passphrase-file"], root)
    kdf = opts.get("kdf") or crypto.KDF_SCRYPT
    files, report = vault.collect(root)
    empty = [plane for plane in report["planes"]
             if not any(rel.startswith(plane + "/") for rel, _ in files)]
    if empty:
        return refuse("private plane(s) hold no bytes: %s. A backup that quietly leaves a plane"
                      " empty says the plane was backed up." % ", ".join(empty))
    before_digest = plane_digest(files)
    row = vault.seal(root, key, kdf)
    blob = vault.container_path(root, row["name"]).read_bytes()
    digest = crypto.container_digest(blob)
    if digest != row["container_sha256"]:
        return refuse("the container on the shelf reads as %s but the seal row recorded %s."
                      % (digest, row["container_sha256"]))
    opened = crypto.open_container(blob, key)
    sealed_digest = plane_digest(opened)
    if sealed_digest != before_digest:
        return refuse("the planes moved while they were being sealed (%s before, %s inside the"
                      " container): the bytes on disk are not the bytes in the backup."
                      % (before_digest, sealed_digest))
    if len(opened) != row["files"]:
        return refuse("the container carries %d entries but the seal row claims %d."
                      % (len(opened), row["files"]))
    envelope = {
        "name": row["name"], "cipher": row["cipher"], "kdf": row["kdf"],
        "container_sha256": digest, "plain_bytes": row["plain_bytes"], "files": row["files"],
        "plane_digest": sealed_digest, "planes": row["planes"],
        "sealed_on": row["host"], "sealed_platform": row["platform"],
        "sealed_python": row["python"], "sealed_at": row["created"],
        "ci_run": opts.get("ci-run") or NOT_A_CI_RUN,
    }
    envelope_path.write_bytes(
        (json.dumps(envelope, sort_keys=True, indent=2) + "\n").encode("utf-8"))
    print("SEALED name=%s files=%d plain_bytes=%d bytes=%d" %
          (row["name"], row["files"], row["plain_bytes"], row["bytes"]))
    print("CIPHER %s kdf=%s container_sha256=%s" % (row["cipher"], row["kdf"], digest))
    print("ON host=%s platform=%s python=%s" % (envelope["sealed_on"], envelope["sealed_platform"],
                                                envelope["sealed_python"]))
    print("PLANES %s plane_digest=%s" % (", ".join(row["planes"]), sealed_digest))
    print("ENVELOPE %s" % envelope_path)
    print("NOT EVIDENCE YET nothing in the repository changed and encrypted_private_backup is"
          " still false; run --restore on a different machine")
    return EXIT_OK


def cmd_restore(root, opts):
    for flag in ("envelope", "passphrase-file", "into"):
        if not opts.get(flag):
            raise ValueError("--restore needs --%s" % flag)
    envelope_path = outside_repo(opts["envelope"], root, "--envelope")
    if not envelope_path.is_file():
        return refuse("--envelope %s is not a file; without it the restoring machine is guessing"
                      " what it should have received." % envelope_path)
    try:
        envelope = json.loads(envelope_path.read_text(encoding="utf-8"))
    except ValueError as exc:
        return refuse("--envelope %s is not JSON: %s" % (envelope_path, exc))
    if not isinstance(envelope, dict):
        return refuse("--envelope %s is not a JSON object" % envelope_path)
    absent = [key for key in ENVELOPE_KEYS if key not in envelope]
    if absent:
        return refuse("--envelope %s carries no %s; a witness that cannot answer those questions"
                      " is not a witness." % (envelope_path, ", ".join(absent)))
    if envelope["cipher"] != vault.CIPHER_CLAIM:
        return refuse("the envelope names cipher %r but this build writes %r: a container from"
                      " another format version is not evidence for this one."
                      % (envelope["cipher"], vault.CIPHER_CLAIM))
    host_law(platform.node(), envelope["sealed_on"], opts)
    key = vault.passphrase_from_file(opts["passphrase-file"], root)
    into = Path(opts["into"])
    if into.exists() and any(into.iterdir()):
        return refuse("--into %s already holds files; a restore mixed into an existing directory"
                      " cannot show which generation the bytes came from." % into)
    before = []
    if into.is_dir():
        before = [str(path) for path in into.rglob("*")]
    try:
        result = vault.restore(root, envelope["name"], into, key)
    except (vault.VaultError, crypto.OpenError, crypto.SealError,
            crypto.UnsupportedKDF) as exc:
        left = [str(path) for path in into.rglob("*")] if into.is_dir() else []
        left = [item for item in left if item not in before]
        print("NOTHING MOVED a failed restore placed %d file(s) under %s" % (len(left), into))
        return refuse("the container did not come back: %s" % exc)
    digest_here, files_here, bytes_here = disk_digest(into)
    problems = []
    if result["container_sha256"] != envelope["container_sha256"]:
        problems.append("container reads as %s, envelope says %s"
                        % (result["container_sha256"], envelope["container_sha256"]))
    if files_here != envelope["files"]:
        problems.append("%d file(s) on disk, envelope says %d" % (files_here, envelope["files"]))
    if bytes_here != envelope["plain_bytes"]:
        problems.append("%d byte(s) restored, envelope says %d" % (bytes_here,
                                                                   envelope["plain_bytes"]))
    if digest_here != envelope["plane_digest"]:
        problems.append("restored plane_digest %s, envelope says %s"
                        % (digest_here, envelope["plane_digest"]))
    if problems:
        return refuse("the round trip does not match: %s" % "; ".join(problems))
    here = platform.node()
    cross_machine = str(here).casefold() != str(envelope["sealed_on"]).casefold()
    print("RESTORED name=%s files=%d plain_bytes=%d" %
          (envelope["name"], files_here, bytes_here))
    print("CIPHER %s kdf=%s container_sha256=%s" % (vault.CIPHER_CLAIM, envelope["kdf"],
                                                    envelope["container_sha256"]))
    print("ON host=%s platform=%s python=%s" % (here, platform.system().lower(),
                                                platform.python_version()))
    print("PLANES %s plane_digest=%s" % (", ".join(envelope["planes"]), digest_here))
    print("SEALED_ON host=%s platform=%s python=%s at=%s ci_run=%s"
          % (envelope["sealed_on"], envelope["sealed_platform"], envelope["sealed_python"],
             envelope["sealed_at"], envelope["ci_run"]))
    print("CROSS_MACHINE %s" % ("true" if cross_machine else "false"))
    if not cross_machine:
        print("NOT EVIDENCE this run is a byte check on one machine; it cannot open"
              " encrypted_private_backup")
    else:
        print("PROOF bytes written on %s (%s) were read back on %s (%s) by python %s"
              % (envelope["sealed_on"], envelope["sealed_platform"], here,
                 platform.system().lower(), platform.python_version()))
    if opts["witness"]:
        draft = {
            "verdict": "roundtrip_pending",
            "cipher": vault.CIPHER_CLAIM,
            "kdf": envelope["kdf"],
            "container_sha256": envelope["container_sha256"],
            "files": envelope["files"],
            "bytes": bytes_here,
            "sealed_on": envelope["sealed_on"],
            "restored_on": here,
            "python_sealed": envelope["sealed_python"],
            "python_restored": platform.python_version(),
            "ci_run": envelope["ci_run"],
            "approved_by": None,
            "approved_at": None,
        }
        print("WITNESS DRAFT (a human reads the run and writes 11_CONTROL/backups/"
              "verification.json; verdict stays roundtrip_pending until then)")
        print(json.dumps(draft, sort_keys=True, indent=2))
    return EXIT_OK


def main(argv, root=None):
    default = Path(root) if root else common.find_root(Path(__file__))
    try:
        opts = parse(argv)
    except ValueError as exc:
        return usage(str(exc))
    root = Path(opts["root"]) if "root" in opts else default
    if not root.is_dir():
        return usage("--root %s is not a directory" % root)
    handlers = {"--fixture": cmd_fixture, "--seal": cmd_seal, "--restore": cmd_restore}
    handler = handlers[opts["command"]]
    try:
        if opts["command"] == "--fixture":
            return handler(str(root))
        return handler(str(root), opts)
    except (vault.VaultError, crypto.OpenError, crypto.SealError, crypto.UnsupportedKDF,
            ValueError) as exc:
        return refuse(str(exc))


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
